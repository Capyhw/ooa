#!/usr/bin/env node
/**
 * sync-antd-tokens.mjs
 *
 * Reads the full antd design-token table from the antd package (getDesignToken),
 * then writes a single OOA token theme to packages/tokens/src/theme.css:
 *
 *   - `:root`                          — light palette (global default, imported by apps).
 *   - `ooa-config-provider[theme="dark"]` — dark palette, scoped to the config-provider
 *     host when its reflected `theme` attribute is `dark` (the app's actual dark
 *     switch — see ooa-config-provider.ts).
 *
 * Every value comes from the **antd source**, not from a browser page, so it is
 * reproducible and free of the runtime's "only rendered components" limitation.
 *
 * Usage (run from the parity app directory, which has antd in node_modules):
 *   node scripts/sync-antd-tokens.mjs [--dry-run]
 */

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const require = createRequire(import.meta.url);

// --------------- helpers ---------------

/**
 * camelCase → kebab-case, matching antd's own CSS-variable naming so each
 * `--ooa-*` maps 1:1 to antd's `--ant-*`.
 *   colorPrimaryHover  →  color-primary-hover
 *   fontSizeSM         →  font-size-sm      (acronym stays one word)
 *   fontSizeXL         →  font-size-xl
 *   fontSizeHeading1   →  font-size-heading-1
 *   blue-1             →  blue-1            (unchanged)
 */
function camelToKebab(s) {
  return s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')   // word boundary before a capital
    .replace(/([a-z])(\d)/g, '$1-$2')         // heading1 → heading-1 (letter→digit only, keeps 10 → -10)
    .toLowerCase();
}

function toOoaVar(name) {
  return '--ooa-' + camelToKebab(name);
}

// Authoritative lists copied from antd (see apps/parity/node_modules/antd/es/theme/useToken.js,
// antd@6.5.0). Mirrored verbatim so the emitted `--ooa-*` matches antd's `--ant-*` set 1:1.
// Unitless tokens are emitted without a length unit (ratios / counts / z-index).
const UNITLESS = new Set([
  'lineHeight',
  'lineHeightSM',
  'lineHeightLG',
  'lineHeightHeading1',
  'lineHeightHeading2',
  'lineHeightHeading3',
  'lineHeightHeading4',
  'lineHeightHeading5',
  'opacityLoading',
  'fontWeightStrong',
  'zIndexPopupBase',
  'zIndexBase',
  'opacityImage',
]);

// Tokens antd deliberately does not emit as CSS variables.
const IGNORE = new Set(['motionBase', 'motionUnit']);

function formatValue(name, value) {
  if (typeof value === 'boolean') return null; // seed flags (motion, wireframe) — antd does not emit them
  if (typeof value === 'string') return value;
  if (typeof value === 'number') {
    return UNITLESS.has(name) ? String(value) : `${value}px`;
  }
  return String(value ?? '');
}

// --------------- resolve antd ---------------

let antdModule;
try {
  antdModule = require('antd');
} catch {
  // Allow running from the repo root via --antd-cwd
  const cwdFlagIdx = process.argv.indexOf('--antd-cwd');
  if (cwdFlagIdx !== -1) {
    const cwd = process.argv[cwdFlagIdx + 1];
    antdModule = require(require.resolve('antd', { paths: [cwd] }));
  } else {
    console.error('Cannot find antd. Run from apps/parity or pass --antd-cwd <dir>');
    process.exit(1);
  }
}

const { getDesignToken, darkAlgorithm } = antdModule.theme;

// --------------- generate ---------------

function generateCss(tokens, selector) {
  const lines = [`${selector} {`];
  const seen = new Set();
  for (const [name, value] of Object.entries(tokens)) {
    if (IGNORE.has(name)) continue;
    const formatted = formatValue(name, value);
    if (formatted === null || formatted === '') continue;
    const cssVarName = toOoaVar(name);
    if (seen.has(cssVarName)) continue; // dedupe blue1 / blue-1 alias pairs
    seen.add(cssVarName);
    lines.push(`  ${cssVarName}: ${formatted};`);
  }
  lines.push('}');
  return lines.join('\n') + '\n';
}

// --------------- main ---------------

const isDryRun = process.argv.includes('--dry-run');

const tokensDir = path.resolve(import.meta.dirname, '..', '..', '..', 'packages', 'tokens', 'src');

const lightTokens = getDesignToken();
const darkTokens = getDesignToken({ algorithm: darkAlgorithm });

const header =
  ['/* Generated by sync-antd-tokens.mjs — do not edit by hand. */',
   '/* Source: antd getDesignToken() — light on :root, dark scoped to <ooa-config-provider theme="dark"> */',
   ''].join('\n');

const combinedCss =
  header + generateCss(lightTokens, ':root') + '\n' + generateCss(darkTokens, 'ooa-config-provider[theme="dark"]');

const themePath = path.join(tokensDir, 'theme.css');

if (isDryRun) {
  const count = (s) => (s.match(/--ooa-[\w-]+:/g) || []).length;
  console.log(`[DRY-RUN] ${Object.keys(lightTokens).length} antd tokens → ${count(combinedCss)} CSS variables`);
  console.log('  ' + themePath);
  console.log('\n--- light preview (first 25 vars) ---');
  console.log(generateCss(lightTokens, ':root').split('\n').slice(1, 26).join('\n'));
} else {
  fs.mkdirSync(tokensDir, { recursive: true });
  fs.writeFileSync(themePath, combinedCss, 'utf-8');
  const count = (s) => (s.match(/--ooa-[\w-]+:/g) || []).length;
  console.log(`${Object.keys(lightTokens).length} antd tokens → ${count(combinedCss)} CSS variables → ${themePath}`);
}
